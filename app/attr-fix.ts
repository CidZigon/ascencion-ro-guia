export function damageTakenFromElements(defElement:string, defLevel?:number){
  const defIndex=ELEMENT_KEYS.indexOf(defElement as ElementKey);
  if(defIndex<0)return null;
  const level=Math.min(4,Math.max(1,defLevel??1));
  const table=PRE_RE_ATTR[level-1];
  return ELEMENT_KEYS.map((element,atkIndex)=>({element,percent:table[atkIndex][defIndex]}));
}
